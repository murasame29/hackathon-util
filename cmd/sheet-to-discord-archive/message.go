package main

import (
	"encoding/json"
	"fmt"
	"strconv"
	"strings"
	"time"
)

type srcUser struct {
	ID         string `json:"id"`
	Username   string `json:"username"`
	GlobalName string `json:"global_name"`
	Avatar     string `json:"avatar"`
}

type srcAttachment struct {
	Filename string `json:"filename"`
	URL      string `json:"url"`
	Size     int64  `json:"size"`
}

type srcMessage struct {
	ID          string            `json:"id"`
	Type        int               `json:"type"`
	Content     string            `json:"content"`
	Timestamp   time.Time         `json:"timestamp"`
	Author      srcUser           `json:"author"`
	Attachments []srcAttachment   `json:"attachments"`
	Embeds      []json.RawMessage `json:"embeds"`
	Reference   *struct {
		Type      int    `json:"type"`
		MessageID string `json:"message_id"`
	} `json:"message_reference"`
	Referenced *srcMessage `json:"referenced_message"`
	Stickers   []struct {
		Name string `json:"name"`
	} `json:"sticker_items"`
	Poll *struct {
		Question struct {
			Text string `json:"text"`
		} `json:"question"`
	} `json:"poll"`
}

var postableTypes = map[int]bool{0: true, 19: true, 20: true, 23: true}

// richEmbeds returns embeds with type "rich" (link previews are regenerated by Discord).
func (m srcMessage) richEmbeds() []json.RawMessage {
	var out []json.RawMessage
	for _, e := range m.Embeds {
		var head struct {
			Type string `json:"type"`
		}
		if json.Unmarshal(e, &head) == nil && head.Type == "rich" {
			out = append(out, e)
		}
	}
	return out
}

func (m srcMessage) extras() []string {
	var out []string
	for _, s := range m.Stickers {
		out = append(out, fmt.Sprintf("[sticker: %s]", s.Name))
	}
	if m.Poll != nil {
		out = append(out, fmt.Sprintf("[poll: %s]", m.Poll.Question.Text))
	}
	return out
}

func isPostable(m srcMessage) bool {
	if !postableTypes[m.Type] {
		return false
	}
	return strings.TrimSpace(m.Content) != "" || len(m.Attachments) > 0 ||
		len(m.richEmbeds()) > 0 || len(m.extras()) > 0
}

func isReply(m srcMessage) bool {
	return m.Reference != nil && m.Reference.Type == 0 && m.Reference.MessageID != ""
}

func avatarURL(u srcUser) string {
	if u.Avatar != "" {
		return fmt.Sprintf("https://cdn.discordapp.com/avatars/%s/%s.png", u.ID, u.Avatar)
	}
	id, _ := strconv.ParseUint(u.ID, 10, 64)
	return fmt.Sprintf("https://cdn.discordapp.com/embed/avatars/%d.png", (id>>22)%6)
}

// splitUploads decides which attachments to upload vs link, given a per-message byte cap.
func splitUploads(atts []srcAttachment, maxBytes int64) (upload, link []srcAttachment) {
	var total int64
	for _, a := range atts {
		total += a.Size
	}
	if total <= maxBytes {
		return atts, nil
	}
	return nil, atts
}

// buildChunks composes the text body (reply prefix, content, extras, links, timestamp) split to fit 2000 chars.
// nameOf resolves an author's display name.
func buildChunks(m srcMessage, linked []srcAttachment, nameOf func(srcUser) string) []string {
	var lines []string
	if isReply(m) && m.Referenced != nil {
		lines = append(lines, replyPrefix(nameOf(m.Referenced.Author), m.Referenced.Content))
	}
	if strings.TrimSpace(m.Content) != "" {
		lines = append(lines, m.Content)
	}
	lines = append(lines, m.extras()...)
	for _, a := range linked {
		lines = append(lines, a.URL)
	}
	lines = append(lines, timestampSuffix(m.Timestamp))
	return splitContent(strings.Join(lines, "\n"), maxContentRunes)
}

func snowflakeLess(a, b string) bool {
	x, _ := strconv.ParseUint(a, 10, 64)
	y, _ := strconv.ParseUint(b, 10, 64)
	return x < y
}

// messagesAfter returns messages (ascending) with ID greater than lastID.
func messagesAfter(msgs []srcMessage, lastID string) []srcMessage {
	if lastID == "" {
		return msgs
	}
	var out []srcMessage
	for _, m := range msgs {
		if snowflakeLess(lastID, m.ID) {
			out = append(out, m)
		}
	}
	return out
}
